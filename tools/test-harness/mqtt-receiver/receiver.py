"""Decode the fill station's MQTT telemetry (temporary test tool; run via run.sh).

Subscribes to everything on the local broker. `rats/pb/0` payloads are decoded
as TelemetryPayload (fill-station/proto/telemetry.proto); `rats/debug/0` is the
optional JSON copy (fill-station `debug-json` feature). Prints a summary each
second, or every message with --all.
"""

import argparse
import json
import threading
import time

import paho.mqtt.client as mqtt
from google.protobuf.message import DecodeError

import telemetry_pb2  # generated by run.sh

PB_TOPIC = "rats/pb/0"
DEBUG_TOPIC = "rats/debug/0"
FLIGHT_MODES = ["Startup", "Standby", "Ascent", "Coast", "DrogueDeployed", "MainDeployed", "Fault"]

lock = threading.Lock()
stats = {"count": 0, "bytes": 0, "errors": 0, "last": None, "last_time": None, "debug": 0}
seen_topics = set()


def describe(p):
    mode = FLIGHT_MODES[p.flight_mode] if p.flight_mode < len(FLIGHT_MODES) else f"?{p.flight_mode}"
    fill = (
        f"pt1={p.pt_1_pressure:.1f} pt2={p.pt_2_pressure:.1f} load={p.load_cell:.2f} "
        f"BV={'open' if p.ball_valve_open else 'closed'} SV1={'open' if p.sv_1_open else 'closed'} "
        f"ign={int(p.ignition)} qd={p.qd_state} t={p.ms_since_boot_fill}ms"
    )
    # FSW fields are all zero when the umbilical is down
    if p.ms_since_boot_cfc:
        fsw = (
            f"mode={mode} SV2={'open' if p.sv_2_open else 'closed'} MAV={'open' if p.mav_open else 'closed'} "
            f"alt={p.altitude:.2f} pt3={p.pt3:.1f} pt4={p.pt4:.1f} cfc_t={p.ms_since_boot_cfc}ms"
        )
    else:
        fsw = "no FSW data (umbilical down)"
    return f"fill: {fill} | fsw: {fsw}"


def on_connect(client, userdata, flags, reason_code, properties):
    print(f"Connected to broker ({reason_code}); waiting for {PB_TOPIC}...")
    client.subscribe("#")


def on_message(client, userdata, msg):
    if msg.topic == PB_TOPIC:
        p = telemetry_pb2.TelemetryPayload()
        try:
            p.ParseFromString(msg.payload)
        except DecodeError as e:
            with lock:
                stats["errors"] += 1
            print(f"DECODE ERROR ({len(msg.payload)} bytes): {e}")
            return
        with lock:
            prev = stats["last"]
            if prev is not None and p.ms_since_boot_fill < prev.ms_since_boot_fill:
                print(f"NOTE: ms_since_boot_fill went backwards "
                      f"({prev.ms_since_boot_fill} -> {p.ms_since_boot_fill}); fill station restarted?")
            stats["count"] += 1
            stats["bytes"] += len(msg.payload)
            stats["last"] = p
            stats["last_time"] = time.monotonic()
        if userdata["all"]:
            print(f"{time.strftime('%H:%M:%S')} {len(msg.payload):3d} B  {describe(p)}")
    elif msg.topic == DEBUG_TOPIC:
        with lock:
            stats["debug"] += 1
        if userdata["all"]:
            print(f"{DEBUG_TOPIC}: {json.dumps(json.loads(msg.payload))[:200]}...")
    elif msg.topic not in seen_topics:
        seen_topics.add(msg.topic)
        print(f"(also seeing topic {msg.topic!r}, {len(msg.payload)} bytes; not decoded)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--port", type=int, default=1883)
    ap.add_argument("--all", action="store_true", help="print every message instead of a 1 s summary")
    args = ap.parse_args()

    client = mqtt.Client(mqtt.CallbackAPIVersion.VERSION2, client_id="mac-receiver",
                         userdata={"all": args.all})
    client.on_connect = on_connect
    client.on_message = on_message
    client.connect(args.host, args.port)
    client.loop_start()

    try:
        while True:
            time.sleep(1)
            if args.all:
                continue
            with lock:
                count, size, errors, debug = stats["count"], stats["bytes"], stats["errors"], stats["debug"]
                last, last_time = stats["last"], stats["last_time"]
                stats.update(count=0, bytes=0, errors=0, debug=0)
            stamp = time.strftime("%H:%M:%S")
            if count:
                extra = f" +{debug} json" if debug else ""
                err = f" {errors} DECODE ERRORS" if errors else ""
                print(f"{stamp} {count:2d} msg/s {size // count:3d} B{extra}{err}  {describe(last)}")
            elif last_time is not None:
                print(f"{stamp} no telemetry for {time.monotonic() - last_time:.0f} s")
    except KeyboardInterrupt:
        pass
    finally:
        client.loop_stop()


if __name__ == "__main__":
    main()
